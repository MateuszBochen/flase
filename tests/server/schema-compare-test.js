// Schema compare: differences of two databases and migration script which makes target the same as source.
// node schema-compare-test.js   (tests/run.sh creates MySQL / MariaDB databases cmp_src and cmp_dst before)
const WebSocket = require('ws');
const BASE = 'http://php_flase:3001';
let failures = 0;
const check = (name, ok, info = '') => { if (!ok) failures++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${info ? '  -- ' + String(info).slice(0, 600) : ''}`); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const MYSQL_SOURCE = [
  "CREATE TABLE customers (id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(150) NOT NULL, city VARCHAR(50) NULL DEFAULT 'Krakow', created_at DATETIME DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_email (email))",
  'CREATE TABLE orders (id INT AUTO_INCREMENT PRIMARY KEY, customer_id INT NOT NULL, total DECIMAL(10,2) NOT NULL DEFAULT 0, KEY idx_customer (customer_id), CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE)',
  'CREATE TABLE order_tags (order_id INT NOT NULL, tag_id INT NOT NULL, PRIMARY KEY (order_id, tag_id), KEY fk_ot_tag (tag_id), CONSTRAINT fk_ot_tag FOREIGN KEY (tag_id) REFERENCES tags (id))',
  'CREATE TABLE tags (id INT PRIMARY KEY, name VARCHAR(30))',
];
const MYSQL_TARGET = [
  'CREATE TABLE customers (id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(100) NOT NULL, phone VARCHAR(20), created_at DATETIME DEFAULT CURRENT_TIMESTAMP)',
  'CREATE TABLE orders (id INT AUTO_INCREMENT PRIMARY KEY, customer_id INT NOT NULL, total DECIMAL(10,2) NOT NULL DEFAULT 0)',
  'CREATE TABLE legacy (id INT PRIMARY KEY)',
];
const PG_SOURCE = [
  "CREATE TABLE customers (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(150) NOT NULL, city VARCHAR(50) DEFAULT 'Krakow', created_at TIMESTAMP DEFAULT now(), CONSTRAINT uq_email UNIQUE (email))",
  'CREATE TABLE tags (id INT PRIMARY KEY, name VARCHAR(30))',
  'CREATE TABLE orders (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id INT NOT NULL REFERENCES customers (id) ON DELETE CASCADE, total NUMERIC(10,2) NOT NULL DEFAULT 0)',
  'CREATE INDEX idx_customer ON orders (customer_id)',
  'CREATE TABLE order_tags (order_id INT NOT NULL, tag_id INT NOT NULL REFERENCES tags (id), PRIMARY KEY (order_id, tag_id))',
];
const PG_TARGET = [
  'CREATE TABLE customers (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(100) NOT NULL, phone VARCHAR(20), created_at TIMESTAMP DEFAULT now())',
  'CREATE TABLE orders (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id INT NOT NULL, total NUMERIC(10,2) NOT NULL DEFAULT 0)',
  'CREATE TABLE legacy (id INT PRIMARY KEY)',
];

/** the same order as migration script of front: foreign keys dropped first, added last, tables dropped at the end */
const scriptOf = (result) => [
  ...result.tables.flatMap((table) => table.dropForeignKeys),
  ...result.tables.filter((table) => table.status !== 'drop').flatMap((table) => table.statements),
  ...result.tables.flatMap((table) => table.addForeignKeys),
  ...result.tables.filter((table) => table.status === 'drop').flatMap((table) => table.statements),
];

(async () => {
  for (const dsn of ['mysql://mariadb', 'mysql://mysql', 'postgresql://postgres:5432/shop']) {
    console.log(`\n=== ${dsn}`);
    const pg = dsn.startsWith('postgresql');
    const connection = {id: 'cmp-' + dsn, dsn, username: 'flase', displayName: dsn, changeConfirmationRequired: false};
    const login = async () => (await fetch(`${BASE}/api/login`, {method: 'POST', headers: {'Content-Type': 'application/json'},
      body: JSON.stringify({userData: {username: 'flase', password: 'flase'}, connectionData: connection})})).json();
    // target is other session (other server in real use) - found by its token
    const [user, targetUser] = [await login(), await login()];
    const ws = new WebSocket(`ws://php_flase:3001/ws/${user.token}`);
    const messages = [];
    ws.on('message', (m) => messages.push(JSON.parse(m)));
    await new Promise((r) => ws.on('open', r));
    const send = (command, payload) => ws.send(JSON.stringify({connectionData: {user, connection}, command, payload}));
    const waitFor = async (fn, ms = 30000) => { const start = Date.now(); while (Date.now() - start < ms) { const v = fn(); if (v) return v; await sleep(30); } return fn(); };
    let seq = 0;
    const execute = async (database, statements) => {
      const tabId = 'cmp-exec' + (++seq);
      send('EXECUTE_STATEMENTS', {tabId, database, statements, stopOnError: true});
      await waitFor(() => messages.find((m) => m.payload?.tabId === tabId && m.message === 'EXECUTION_FINISHED'));
      return messages.filter((m) => m.payload?.tabId === tabId && m.message === 'STATEMENT_FINISHED').map((m) => m.payload).filter((f) => f.error);
    };
    const compare = async (source, target, token = targetUser.token) => {
      const tabId = 'cmp' + (++seq);
      send('COMPARE_SCHEMA', {tabId, database: source, target: {token, database: target}});
      return (await waitFor(() => messages.find((m) => m.payload?.tabId === tabId && (m.message === 'SCHEMA_COMPARE' || m.message === 'QUERY_ERROR'))));
    };

    if (pg) {
      const errors = await execute('public', ['DROP SCHEMA IF EXISTS cmp_src CASCADE', 'DROP SCHEMA IF EXISTS cmp_dst CASCADE', 'CREATE SCHEMA cmp_src', 'CREATE SCHEMA cmp_dst',
        ...PG_SOURCE.map((sql) => sql.replace(/^CREATE (TABLE|INDEX) (\w+)( ON )?(\w+)?/, (all, kind, name, on, table) => kind === 'TABLE' ? `CREATE TABLE cmp_src.${name}` : `CREATE INDEX ${name} ON cmp_src.${table}`)
          .replace(/REFERENCES (\w+)/g, 'REFERENCES cmp_src.$1')),
        ...PG_TARGET.map((sql) => sql.replace(/^CREATE TABLE (\w+)/, 'CREATE TABLE cmp_dst.$1'))]);
      check('setup', !errors.length, JSON.stringify(errors));
    } else {
      const errors = [...await execute('cmp_src', ['SET FOREIGN_KEY_CHECKS = 0', 'DROP TABLE IF EXISTS order_tags, orders, tags, customers, legacy', 'SET FOREIGN_KEY_CHECKS = 1', MYSQL_SOURCE[0], MYSQL_SOURCE[3], MYSQL_SOURCE[1], MYSQL_SOURCE[2]]),
        ...await execute('cmp_dst', ['SET FOREIGN_KEY_CHECKS = 0', 'DROP TABLE IF EXISTS order_tags, orders, tags, customers, legacy', 'SET FOREIGN_KEY_CHECKS = 1', ...MYSQL_TARGET])];
      check('setup', !errors.length, JSON.stringify(errors));
    }

    let r = await compare('cmp_src', 'cmp_dst');
    check('compare answered', r?.message === 'SCHEMA_COMPARE', JSON.stringify(r?.payload).slice(0, 300));
    const result = r.payload;
    const byName = Object.fromEntries((result.tables || []).map((table) => [table.name, table]));
    check('new tables, referenced first', byName.tags?.status === 'create' && byName.order_tags?.status === 'create'
      && result.tables.findIndex((table) => table.name === 'tags') < result.tables.findIndex((table) => table.name === 'order_tags'), JSON.stringify(result.tables?.map((t) => t.name)));
    check('table only in target is dropped', byName.legacy?.status === 'drop' && /DROP TABLE/i.test(byName.legacy.statements.join()), JSON.stringify(byName.legacy));
    const customers = byName.customers?.changes.join(' | ') || '';
    check('changed columns found', /add column city/.test(customers) && /drop column phone/.test(customers) && /change column email: type varchar\(100\) → varchar\(150\)/i.test(customers)
      && /add unique index uq_email/.test(customers), customers);
    check('created_at is the same', !/created_at/.test(customers), customers);
    const orders = byName.orders?.changes.join(' | ') || '';
    check('index and foreign key found', /add index idx_customer/.test(orders) && /add foreign key \(customer_id\) → customers/.test(orders), orders);
    check('foreign key added after tables', byName.orders.addForeignKeys.length === 1 && !byName.orders.statements.some((sql) => /FOREIGN KEY/i.test(sql)), JSON.stringify(byName.orders));
    check('views not compared, no warnings of tables', result.tables.every((table) => !table.warnings.length), JSON.stringify(result.tables.map((t) => t.warnings)));

    // script makes target the same
    const script = scriptOf(result);
    const errors = await execute('cmp_dst', script);
    check('migration script runs', !errors.length, JSON.stringify(errors) + '\n' + script.join(';\n'));
    r = await compare('cmp_src', 'cmp_dst');
    check('after migration databases are the same', r?.payload?.tables?.length === 0 && r.payload.same === 4, JSON.stringify(r?.payload?.tables));

    // the same session as target, wrong token
    r = await compare('cmp_src', 'cmp_src', user.token);
    check('database compared with itself', r?.payload?.tables?.length === 0, JSON.stringify(r?.payload).slice(0, 200));
    r = await compare('cmp_src', 'cmp_dst', 'nope');
    check('unknown target session -> error', r?.message === 'QUERY_ERROR' && /not logged in/.test(r.payload.error), JSON.stringify(r?.payload));
    r = await compare('cmp_nope', 'cmp_dst');
    check('missing source database -> error or empty', r?.message === 'QUERY_ERROR' || r?.payload?.tables?.every((t) => t.status === 'drop'), JSON.stringify(r?.payload).slice(0, 200));

    if (pg) await execute('public', ['DROP SCHEMA IF EXISTS cmp_src CASCADE', 'DROP SCHEMA IF EXISTS cmp_dst CASCADE']);
    ws.close();
    for (const token of [user.token, targetUser.token]) {
      await fetch(`${BASE}/api/disconnect`, {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({token})});
    }
  }
  console.log(failures ? `\n${failures} FAILED` : '\nALL PASSED');
  process.exit(failures ? 1 : 0);
})();
